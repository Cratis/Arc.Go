func TestProductionCLIServiceBindingsExternalCompiledWitness(t *testing.T) {
	dir := consumer(t)
	fixture := filepath.Join("testdata", "servicebindings")
	source := get(t, filepath.Join(fixture, "input.go.txt"))
	if bytes.Contains(source, []byte("func RegisterServices")) {
		t.Fatal("handwritten renderer witness")
	}
	put(t, filepath.Join(dir, "input.go"), string(source))
	put(t, filepath.Join(dir, "bindings.json"), string(get(t, filepath.Join(fixture, "bindings.json"))))
	cli := func(extra ...string) []byte {
		t.Helper()
		ctx, cancel := context.WithTimeout(t.Context(), 45*time.Second)
		defer cancel()
		args := []string{"run", "./cmd/arc-gen", "-dir", dir, "-bindings-config", filepath.Join(dir, "bindings.json")}
		args = append(args, extra...)
		args = append(args, ".")
		command := exec.CommandContext(ctx, "go", args...)
		command.Dir = "../.."
		command.Env = append(os.Environ(), "GOWORK=off", "GOTOOLCHAIN=local", "ARC_BINDINGS_GENERATION=trap")
		output, err := command.CombinedOutput()
		if err != nil {
			t.Fatalf("production CLI: %v\n%s", err, output)
		}
		return output
	}
	inventory := cli()
	if !bytes.Contains(inventory, []byte("service bindings published")) || bytes.Contains(inventory, []byte("0 service bindings")) {
		t.Fatal(string(inventory))
	}
	first := get(t, filepath.Join(dir, Filename))
	cli()
	if !bytes.Equal(first, get(t, filepath.Join(dir, Filename))) {
		t.Fatal("production bytes differ")
	}
	cli("-check")
	for _, name := range []string{"BindFunc1", "BindFunc2", "BindFunc3", "BindFunc4", "BindBorrowed", "NewWide("} {
		if !bytes.Contains(first, []byte(name)) {
			t.Fatalf("missing production inventory %s", name)
		}
	}
	if bytes.Contains(first, []byte("BindFunc0")) {
		t.Fatal("nonexistent adapter")
	}
	// Inspect actual resolved modules, not merely the fixture's requested manifest.
	ctx, cancel := context.WithTimeout(t.Context(), 45*time.Second)
	defer cancel()
	command := exec.CommandContext(ctx, "go", "list", "-m", "-json", "all")
	command.Dir = dir
	command.Env = append(os.Environ(), "GOWORK=off", "GOTOOLCHAIN=local")
	output, err := command.CombinedOutput()
	if err != nil {
		t.Fatalf("resolved module pins: %v\n%s", err, output)
	}
	decoder := json.NewDecoder(bytes.NewReader(output))
	found := map[string]bool{}
	pins := map[string]string{runtimePath: "v0.0.0-20261003142617-78ebbf8fdff8", "github.com/cratis/fundamentals.go": "v0.2.0"}
	checkout, err := filepath.Abs("../../..")
	if err != nil {
		t.Fatal(err)
	}
	for decoder.More() {
		var module struct {
			Path, Version, Dir string
			Replace            *json.RawMessage
		}
		if err := decoder.Decode(&module); err != nil {
			t.Fatal(err)
		}
		if module.Replace != nil {
			t.Fatalf("replacement source: %+v", module)
		}
		if pin, ok := pins[module.Path]; ok {
			if module.Version != pin || module.Dir == "" || strings.HasPrefix(module.Dir, checkout+string(os.PathSeparator)) {
				t.Fatalf("unqualified pin/source: %+v", module)
			}
			found[module.Path] = true
		}
	}
	if len(found) != len(pins) {
		t.Fatal("pins not resolved", found)
	}
	put(t, filepath.Join(dir, "graphs", "input.go"), string(get(t, filepath.Join(fixture, "graphs.go.txt"))))
	graphConfig := bindingsConfig(t, dir, serviceBindingsConfig{Package: "example.test/consumer/graphs"})
	runServiceCLI(t, dir, graphConfig, "./graphs")
	put(t, filepath.Join(dir, "graphs_test.go"), string(get(t, filepath.Join(fixture, "graphs_test.go.txt"))))
	put(t, filepath.Join(dir, "contract_test.go"), string(get(t, filepath.Join(fixture, "contract_test.go.txt"))))
	ctxRun, cancelRun := context.WithTimeout(t.Context(), 45*time.Second)
	defer cancelRun()
	command = exec.CommandContext(ctxRun, "go", "test", "-mod=mod", "-count=1", "-timeout=30s", "./...")
	command.Dir = dir
	command.Env = append(os.Environ(), "GOWORK=off", "GOTOOLCHAIN=local")
	if output, err := command.CombinedOutput(); err != nil {
		t.Fatalf("external generated service/runtime witness: %v\n%s", err, output)
	}
}
