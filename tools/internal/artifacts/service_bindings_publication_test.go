	config := Config{Dir: dir, BindingsConfigFile: bindingsConfig(t, dir, serviceBindingsConfig{})}
	generate(t, config)
	data := get(t, filepath.Join(dir, Filename))
	// Dep is a constructor edge, not a callback or command stage key.
	if bytes.Contains(data, []byte("ResolveDep")) || bytes.Count(data, []byte("KeyFor[*Dep]")) != 0 || !bytes.Contains(data, []byte("BindFunc1")) {
		t.Fatal(string(data))
	}
